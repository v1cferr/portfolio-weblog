/**
 * Generates src/generated/icons.ts from the icon references in content/:
 *
 *   pnpm icons:sync          write the file
 *   pnpm icons:sync --check  fail if it is missing an icon or out of date (CI)
 *
 * Only the icons the content uses end up in the site. Brand logos come from
 * Simple Icons (si:, CC0) and Devicon (dv:, MIT; the monochrome "plain"
 * variant), and render as inline SVG in currentColor. Lucide icons (lucide:)
 * are re-exported as components so they tree-shake.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

import { findContentRoot, loadContent } from "@workspace/content";
import * as lucide from "lucide-react";
import * as simpleIcons from "simple-icons";

const require = createRequire(import.meta.url);
const OUTPUT = path.join(import.meta.dirname, "..", "src", "generated", "icons.ts");
const check = process.argv.includes("--check");

const { content } = loadContent(findContentRoot());
const refs = new Set<string>();
for (const { value } of content.technologies) if (value.icon !== undefined) refs.add(value.icon);
const links = [
  ...(content.profile?.value.links ?? []),
  ...content.experiences.flatMap(({ value }) => value.evidence),
  ...content.projects.flatMap(({ value }) => value.links),
  ...content.education.flatMap(({ value }) => value.evidence),
];
for (const link of links) if (link.icon !== undefined) refs.add(link.icon);

const errors: string[] = [];
const brands: Record<string, { title: string; hex: string; viewBox: string; body: string }> = {};
const lucideRefs: Record<string, string> = {};

const bySlug = new Map(
  Object.values(simpleIcons as Record<string, { slug: string; title: string; hex: string; path: string }>).map((icon) => [icon.slug, icon])
);
const pascal = (kebab: string) => kebab.replace(/(^|-)([a-z0-9])/g, (_match: string, _dash: string, char: string) => char.toUpperCase());

for (const ref of [...refs].sort()) {
  const [source = "", name = ""] = ref.split(":");
  if (source === "si") {
    const icon = bySlug.get(name);
    if (icon === undefined) errors.push(`${ref}: not in Simple Icons`);
    else brands[ref] = { title: icon.title, hex: `#${icon.hex}`, viewBox: "0 0 24 24", body: `<path d="${icon.path}"/>` };
  } else if (source === "dv") {
    let svg: string;
    try {
      svg = readFileSync(require.resolve(`devicon/icons/${name}/${name}-plain.svg`), "utf8");
    } catch {
      errors.push(`${ref}: Devicon has no ${name}-plain.svg`);
      continue;
    }
    const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? "0 0 128 128";
    // Monochrome: drop every colour and style so the icon follows currentColor.
    const body = svg
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>\s*$/, "")
      .replace(/\s(?:fill|stroke|style|class)="[^"]*"/g, "")
      .replace(/\s+/g, " ")
      .trim();
    brands[ref] = { title: name, hex: "", viewBox, body };
  } else if (source === "lucide") {
    const component = `${pascal(name)}Icon`;
    if (!(component in lucide)) errors.push(`${ref}: lucide-react has no ${component}`);
    else lucideRefs[ref] = component;
  }
}

if (errors.length > 0) {
  console.error(`Unknown icons:\n${errors.map((error) => `  - ${error}`).join("\n")}`);
  process.exit(1);
}

const components = [...new Set(Object.values(lucideRefs))].sort();
const output = `// Generated by \`pnpm icons:sync\` from the icon references in content/. Do not edit.
import { ${components.join(", ")} } from "lucide-react";

export const brandIcons: Record<string, { title: string; hex: string; viewBox: string; body: string }> = ${JSON.stringify(brands, null, 2)};

export const lucideIcons = {
${Object.entries(lucideRefs)
  .map(([ref, component]) => `  ${JSON.stringify(ref)}: ${component},`)
  .join("\n")}
};
`;

let current = "";
try {
  current = readFileSync(OUTPUT, "utf8");
} catch {
  // first run
}
if (check) {
  if (current !== output) {
    console.error("src/generated/icons.ts is out of date; run pnpm icons:sync");
    process.exit(1);
  }
  console.warn(`Icons OK (${String(Object.keys(brands).length)} brand, ${String(components.length)} lucide)`);
} else {
  writeFileSync(OUTPUT, output);
  console.warn(
    `Wrote ${path.relative(process.cwd(), OUTPUT)}: ${String(Object.keys(brands).length)} brand icons, ${String(components.length)} lucide icons`
  );
}
