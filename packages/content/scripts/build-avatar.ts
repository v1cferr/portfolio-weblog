/**
 * Builds the hero avatar's ASCII art from the hero photo:
 *
 *   pnpm avatar:build
 *
 * Input: apps/web/public/images/hero.jpg (the owner beside the FAI·UFSCar
 * sign, cropped and with the ID badge blurred; no metadata).
 * Output: apps/web/src/generated/avatar-ascii.ts, one grid per theme. The
 * page renders it as SVG text and reveals the photo through a lens around
 * the pointer (features/profile/avatar.tsx).
 *
 * Chosen on 2026-11-22 from a side-by-side comparison: monochrome glyphs in
 * the theme's ink, colour only where the photo is vivid (the FAI logo and the
 * red "inovação"), 120 columns.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";

import sharp from "sharp";

import { asciiArt, findContentRoot } from "../src";

const COLUMNS = 120;
/** Glyph cells are 0.6 as wide as they are tall (the SVG draws them at 6 × 10 units). */
const CELL_ASPECT = 0.6;

const web = path.join(findContentRoot(), "..", "apps", "web");
const photo = path.join(web, "public", "images", "hero.jpg");
const target = path.join(web, "src", "generated", "avatar-ascii.ts");

const { width, height } = await sharp(photo).metadata();
const rows = Math.round(COLUMNS * (height / width) * CELL_ASPECT);
const rgb = await sharp(photo).removeAlpha().resize(COLUMNS, rows, { fit: "fill", kernel: "lanczos3" }).raw().toBuffer();

const grids = {
  light: asciiArt(rgb, COLUMNS, rows, { theme: "light" }),
  dark: asciiArt(rgb, COLUMNS, rows, { theme: "dark" }),
};

await writeFile(
  target,
  `// Generated by \`pnpm avatar:build\` from public/images/hero.jpg. Do not edit.
import type { AsciiRow } from "@workspace/content";

export const avatarAscii: { columns: number; rows: number; photo: { width: number; height: number }; light: AsciiRow[]; dark: AsciiRow[] } = ${JSON.stringify(
    {
      columns: COLUMNS,
      rows,
      photo: { width, height },
      ...grids,
    }
  )};
`
);

console.warn(`Wrote ${path.relative(process.cwd(), target)} (${String(COLUMNS)} × ${String(rows)} glyphs per theme)`);
